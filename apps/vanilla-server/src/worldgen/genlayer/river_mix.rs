//! Isolated Minecraft Java 1.7.10 GenLayerRiverMix.
//!
//! Combines the biome and river layers using vanilla biome IDs. This is not
//! connected to the persisted IRW4 generator: changing the latter would alter
//! untouched chunks in existing worlds after a restart.

/// Merge two same-resolution GenLayer maps. No random numbers are consumed.
/// The parents are evaluated at identical coordinates, including negatives.
pub(super) fn river_mix_map<B, R>(
    x: i32,
    z: i32,
    width: usize,
    height: usize,
    biome_parent: B,
    river_parent: R,
) -> Vec<i32>
where
    B: Fn(i32, i32, usize, usize) -> Vec<i32>,
    R: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    let biomes = biome_parent(x, z, width, height);
    let rivers = river_parent(x, z, width, height);
    assert_eq!(biomes.len(), width * height);
    assert_eq!(rivers.len(), width * height);

    biomes
        .into_iter()
        .zip(rivers)
        .map(|(biome, river)| {
            if biome == 0 || biome == 24 || river != 7 {
                // Ocean, Deep Ocean and cells without a river are unchanged.
                biome
            } else {
                match biome {
                    12 => 11,      // Ice Plains -> Frozen River
                    14 | 15 => 15, // Mushroom Island/Shore -> Mushroom Shore
                    _ => river & 255,
                }
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_independent_java_1_7_10_river_mix_oracle() {
        // Generated by tools/GenLayerRiverMixOracle.java, which follows
        // Minecraft 1.7.10's branch ordering, not this Rust implementation.
        let biomes = [0, 24, 12, 14, 15, 1, 4, 3, 30, 2, 7, 11, 13, 16, 21, 35];
        let rivers = [7, 7, 7, 7, 7, 7, -1, 7, 7, 7, -1, 7, 7, 7, 7, 7];
        assert_eq!(
            river_mix_map(
                -17,
                15,
                4,
                4,
                |_, _, _, _| biomes.to_vec(),
                |_, _, _, _| rivers.to_vec()
            ),
            [0, 24, 11, 15, 15, 7, 4, 7, 7, 7, 7, 7, 7, 7, 7, 7]
        );
    }

    #[test]
    fn only_exact_river_id_seven_overlays_biomes() {
        let biomes = [12, 14, 1, 12, 24, 0];
        let rivers = [-1, 0, 263, 7, 7, 7];
        assert_eq!(
            river_mix_map(
                0,
                0,
                3,
                2,
                |_, _, _, _| biomes.to_vec(),
                |_, _, _, _| rivers.to_vec()
            ),
            [12, 14, 1, 11, 24, 0]
        );
    }

    #[test]
    fn negative_chunk_boundaries_and_split_requests_match() {
        let biome_parent = |x: i32, z: i32, width: usize, height: usize| {
            let palette = [0, 24, 12, 14, 15, 1, 4, 3, 30, 2];
            let mut values = Vec::with_capacity(width * height);
            for dz in 0..height {
                for dx in 0..width {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    values.push(palette[((px ^ pz) & 15) as usize % palette.len()]);
                }
            }
            values
        };
        let river_parent = |x: i32, z: i32, width: usize, height: usize| {
            let mut values = Vec::with_capacity(width * height);
            for dz in 0..height {
                for dx in 0..width {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    values.push(if (px ^ pz).rem_euclid(3) == 0 { 7 } else { -1 });
                }
            }
            values
        };
        let whole = river_mix_map(-17, -17, 8, 8, biome_parent, river_parent);
        for dz in (0..8).rev() {
            for dx in (0..8).rev() {
                let cell = river_mix_map(
                    -17 + dx,
                    -17 + dz,
                    1,
                    1,
                    biome_parent,
                    river_parent,
                );
                assert_eq!(cell[0], whole[(dz * 8 + dx) as usize]);
            }
        }
    }

    #[test]
    fn empty_requests_do_not_evaluate_parents() {
        assert!(river_mix_map(
            0,
            0,
            0,
            8,
            |_, _, _, _| panic!("biome parent evaluated"),
            |_, _, _, _| panic!("river parent evaluated"),
        )
        .is_empty());
    }
}
