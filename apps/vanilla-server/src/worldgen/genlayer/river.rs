//! Isolated Minecraft Java 1.7.10 GenLayerRiverInit and GenLayerRiver.
//!
//! These are layer-cell maps, not the live IRW4 river generator. Connecting
//! them to new worlds requires a separate persisted generation version.
use super::GenLayerRng;

/// Turn positive land cells into deterministic pseudo-random values >= 2.
/// Vanilla uses nextInt(299999) + 2 and leaves ocean cells at zero.
pub(super) fn river_init_map<F>(
    world_seed: i64,
    layer_salt: i64,
    x: i32,
    z: i32,
    width: usize,
    height: usize,
    parent: F,
) -> Vec<i32>
where
    F: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    let source = parent(x, z, width, height);
    assert_eq!(source.len(), width * height);
    let mut result = vec![0; width * height];
    let mut rng = GenLayerRng::new(world_seed, layer_salt);
    for dz in 0..height {
        for dx in 0..width {
            let index = dz * width + dx;
            if source[index] > 0 {
                // Java adds cell offsets as signed 32-bit ints before
                // widening them to long for initChunkSeed.
                rng.start_chunk(
                    i64::from(x.wrapping_add(dx as i32)),
                    i64::from(z.wrapping_add(dz as i32)),
                );
                result[index] = rng.next_int(299_999) + 2;
            }
        }
    }
    result
}

/// River compares only parity for the positive values generated by RiverInit.
/// Ocean (0) and no-river (-1) remain distinct from those values.
fn river_value(value: i32) -> i32 {
    if value >= 2 {
        2 + (value & 1)
    } else {
        value
    }
}

/// Return vanilla river biome ID 7 at parity boundaries, -1 elsewhere.
/// The parent must provide a one-cell halo on each side.
pub(super) fn river_map<F>(x: i32, z: i32, width: usize, height: usize, parent: F) -> Vec<i32>
where
    F: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    let stride = width + 2;
    let source = parent(x.wrapping_sub(1), z.wrapping_sub(1), stride, height + 2);
    assert_eq!(source.len(), stride * (height + 2));
    let mut result = vec![-1; width * height];
    for dz in 0..height {
        for dx in 0..width {
            let north = river_value(source[dz * stride + dx + 1]);
            let south = river_value(source[(dz + 2) * stride + dx + 1]);
            let west = river_value(source[(dz + 1) * stride + dx]);
            let east = river_value(source[(dz + 1) * stride + dx + 2]);
            let center = river_value(source[(dz + 1) * stride + dx + 1]);
            if center != north || center != south || center != west || center != east {
                result[dz * width + dx] = 7;
            }
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn patterned_parent(x: i32, z: i32, width: usize, height: usize) -> Vec<i32> {
        let mut values = Vec::with_capacity(width * height);
        for dz in 0..height {
            for dx in 0..width {
                let px = x.wrapping_add(dx as i32);
                let pz = z.wrapping_add(dz as i32);
                values.push(i32::from(((px ^ pz) & 3) != 0));
            }
        }
        values
    }

    #[test]
    fn river_init_matches_independent_java_long_oracle() {
        // Java 21 standalone oracle with seed mixing and patterned_parent.
        // Values are row-major 4x4, including negative layer coordinates.
        for (seed, x, z, expected) in [
            (
                42,
                -17,
                7,
                [
                    0, 200180, 67228, 104735, 162757, 0, 67680, 53593, 242866, 196279, 0, 166102,
                    82371, 82228, 92907, 0,
                ],
            ),
            (
                -12_345,
                -1,
                -1,
                [
                    0, 202994, 275038, 154255, 68591, 0, 37521, 51931, 270528, 30686, 0, 43064,
                    82196, 104695, 231861, 0,
                ],
            ),
            (
                0,
                15,
                -17,
                [
                    0, 95386, 95058, 17879, 188901, 0, 267528, 220190, 254762, 28541, 0, 123506,
                    263510, 222818, 261019, 0,
                ],
            ),
        ] {
            assert_eq!(
                river_init_map(seed, 100, x, z, 4, 4, patterned_parent),
                expected,
                "seed={seed} at ({x},{z})"
            );
        }
    }

    #[test]
    fn river_init_is_independent_of_request_order() {
        let whole = river_init_map(42, 100, -17, -17, 8, 8, patterned_parent);
        for dz in (0..8).rev() {
            for dx in (0..8).rev() {
                let single = river_init_map(42, 100, -17 + dx, -17 + dz, 1, 1, patterned_parent);
                assert_eq!(single[0], whole[(dz * 8 + dx) as usize]);
            }
        }
        assert!(river_init_map(42, 100, 0, 0, 0, 8, patterned_parent).is_empty());
    }

    #[test]
    fn river_detects_parity_edges_but_not_equal_parity_values() {
        assert_eq!(
            river_map(0, 0, 4, 4, |_, _, w, h| vec![2; w * h]),
            vec![-1; 16]
        );
        assert_eq!(
            river_map(0, 0, 1, 1, |_, _, _, _| vec![2, 2, 2, 2, 3, 2, 2, 2, 2]),
            vec![7]
        );
        assert_eq!(
            river_map(0, 0, 1, 1, |_, _, _, _| vec![2, 2, 2, 2, 4, 2, 2, 2, 2]),
            vec![-1]
        );
    }

    #[test]
    fn river_has_no_seams_across_negative_chunk_boundaries() {
        let parent = |x: i32, z: i32, width: usize, height: usize| {
            let mut values = Vec::with_capacity(width * height);
            for dz in 0..height {
                for dx in 0..width {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    values.push(if (px ^ pz).rem_euclid(7) == 0 { 3 } else { 2 });
                }
            }
            values
        };
        let whole = river_map(-17, -17, 8, 8, parent);
        assert!(whole.contains(&7));
        assert!(whole.contains(&-1));
        for dz in (0..8).rev() {
            for dx in (0..8).rev() {
                let cell = river_map(-17 + dx, -17 + dz, 1, 1, parent);
                assert_eq!(cell[0], whole[(dz * 8 + dx) as usize]);
            }
        }
        assert!(river_map(0, 0, 8, 0, parent).is_empty());
    }

    #[test]
    fn river_init_wraps_java_int_coordinates_at_both_boundaries() {
        // Independent Python verification of Java-long GenLayerRiverInit
        // with the same patterned parent as the other golden fixtures.
        // Java int addition wraps before initChunkSeed(long, long).
        let cases: [(i64, i32, i32, [i32; 12]); 2] = [
            (
                42,
                i32::MAX - 1,
                i32::MAX - 1,
                [
                    0, 251901, 137239, 178700, 298966, 0, 79446, 70386, 207052, 242802, 0, 240650,
                ],
            ),
            (
                -12_345,
                i32::MAX,
                i32::MIN,
                [
                    61330, 0, 241381, 236981, 19420, 267753, 0, 77482, 56220, 151332, 81672, 0,
                ],
            ),
        ];
        for (seed, x, z, expected) in cases {
            let whole = river_init_map(seed, 100, x, z, 4, 3, patterned_parent);
            assert_eq!(whole, expected, "seed={seed} at ({x},{z})");
            for dz in 0..3 {
                for dx in 0..4 {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    let cell = river_init_map(seed, 100, px, pz, 1, 1, patterned_parent);
                    assert_eq!(cell[0], whole[dz * 4 + dx]);
                }
            }
        }
    }
}
