//! Isolated Minecraft Java 1.7.10 GenLayerEdge climate transitions.
//!
//! The live IRW4 generator and persisted chunks are deliberately unchanged.
use super::GenLayerRng;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub(super) enum EdgeMode {
    CoolWarm,
    HeatIce,
    Special,
}

/// Apply one vanilla Edge mode to a rectangular climate map.
/// CoolWarm and HeatIce read a one-cell parent border; Special reads the
/// exact rectangle and applies the high-byte climate marker with Java RNG.
/// Parent coordinates use Java signed-int wrapping at coordinate boundaries.
pub(super) fn edge_map<F>(
    world_seed: i64,
    layer_salt: i64,
    mode: EdgeMode,
    x: i32,
    z: i32,
    width: usize,
    height: usize,
    parent: F,
) -> Vec<i32>
where
    F: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    let bordered = mode != EdgeMode::Special;
    let parent_width = if bordered { width + 2 } else { width };
    let parent_height = if bordered { height + 2 } else { height };
    let parent_x = if bordered { x.wrapping_sub(1) } else { x };
    let parent_z = if bordered { z.wrapping_sub(1) } else { z };
    let source = parent(parent_x, parent_z, parent_width, parent_height);
    assert_eq!(source.len(), parent_width * parent_height);

    let mut result = vec![0; width * height];
    let mut rng = GenLayerRng::new(world_seed, layer_salt);
    for dz in 0..height {
        for dx in 0..width {
            let index = dz * width + dx;
            let center_index = if bordered {
                (dz + 1) * parent_width + dx + 1
            } else {
                index
            };
            let mut climate = source[center_index];
            match mode {
                EdgeMode::CoolWarm if climate == 1 => {
                    let neighbors = [
                        source[center_index - parent_width],
                        source[center_index + 1],
                        source[center_index - 1],
                        source[center_index + parent_width],
                    ];
                    if neighbors.iter().any(|&value| value == 3 || value == 4) {
                        climate = 2;
                    }
                }
                EdgeMode::HeatIce if climate == 4 => {
                    let neighbors = [
                        source[center_index - parent_width],
                        source[center_index + 1],
                        source[center_index - 1],
                        source[center_index + parent_width],
                    ];
                    if neighbors.iter().any(|&value| value == 1 || value == 2) {
                        climate = 3;
                    }
                }
                EdgeMode::Special => {
                    let cell_x = x.wrapping_add(dx as i32);
                    let cell_z = z.wrapping_add(dz as i32);
                    rng.start_chunk(i64::from(cell_x), i64::from(cell_z));
                    if climate != 0 && rng.next_int(13) == 0 {
                        climate |= ((1 + rng.next_int(15)) << 8) & 3840;
                    }
                }
                _ => {}
            }
            result[index] = climate;
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn patterned_parent(x: i32, z: i32, width: usize, height: usize) -> Vec<i32> {
        let palette = [0, 1, 3, 4, 2, 1, 4, 3];
        let mut values = Vec::with_capacity(width * height);
        for dz in 0..height {
            for dx in 0..width {
                let px = x.wrapping_add(dx as i32);
                let pz = z.wrapping_add(dz as i32);
                values.push(palette[((px ^ pz) & 7) as usize]);
            }
        }
        values
    }

    fn hex_rows(values: &[i32]) -> Vec<String> {
        values
            .chunks(8)
            .map(|row| {
                row.iter()
                    .map(|v| format!("{v:04x}"))
                    .collect::<Vec<_>>()
                    .concat()
            })
            .collect()
    }

    #[test]
    fn matches_independent_java_1_7_10_edge_oracle() {
        // Generated by tools/GenLayerEdgeOracle.java with Java long overflow.
        let cool_warm = [
            "00000003000400020002000400030002",
            "00030000000200030004000200020004",
            "00040002000000040003000200020003",
            "00020003000400000002000400030002",
            "00020004000300020000000300040002",
            "00040002000200040003000000020003",
            "00030002000200030004000200000004",
            "00020004000300020002000300040000",
        ];
        let heat_ice = [
            "00000003000300010002000300030001",
            "00030000000100030003000200010003",
            "00030001000000040003000100020003",
            "00010003000400000001000300030002",
            "00020003000300010000000300030001",
            "00030002000100030003000000010003",
            "00030001000200030003000100000004",
            "00010003000300020001000300040000",
        ];
        for (mode, expected) in [
            (EdgeMode::CoolWarm, cool_warm),
            (EdgeMode::HeatIce, heat_ice),
        ] {
            let actual = edge_map(42, 2, mode, -17, -17, 8, 8, patterned_parent);
            assert_eq!(hex_rows(&actual), expected, "mode={mode:?}");
        }
        let special_cases = [
            (
                42,
                -17,
                -17,
                [
                    "00000003000406010002000400030001",
                    "00030000000100030a04000208010004",
                    "00040001000000040003000100020003",
                    "00010003000400000001000400030302",
                    "0002000409030c010000000300040001",
                    "05040002000100040003000000010003",
                    "00030a01000200030004000100000004",
                    "00010004000300020001000300040000",
                ],
            ),
            (
                -12_345,
                15,
                -17,
                [
                    "00000003000400010502000400030001",
                    "00030000000100030004000200010004",
                    "00040001000000040f03000100020003",
                    "00010003000400000001000400030002",
                    "00020004000300010000030300040001",
                    "00040002000100040003000000010603",
                    "00030001000200030004000100000c04",
                    "00010004000300020b01000300040000",
                ],
            ),
            (
                i64::MAX,
                -1,
                -1,
                [
                    "00000003000400010102010400030001",
                    "00030000000100030004000200010004",
                    "00040001000000040003000100020003",
                    "00010003000400000001000400030002",
                    "000200040a0305010000000300040001",
                    "00040002000100040003000000010003",
                    "00030001000200030004000100000004",
                    "00010804000300020001000300040000",
                ],
            ),
        ];
        for (seed, x, z, expected) in special_cases {
            let actual = edge_map(seed, 3, EdgeMode::Special, x, z, 8, 8, patterned_parent);
            assert_eq!(hex_rows(&actual), expected, "seed={seed} at ({x},{z})");
        }
    }

    #[test]
    fn inserts_intermediate_climates_only_for_cardinal_neighbors() {
        let parent = |x: i32, z: i32, width: usize, height: usize| {
            let mut values = Vec::with_capacity(width * height);
            for dz in 0..height {
                for dx in 0..width {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    let climate = match (px, pz) {
                        (0, 0) => 1,
                        (1, 0) => 4,
                        (4, 0) => 4,
                        (5, 0) => 1,
                        (0, 4) => 4,
                        (1, 5) => 1,
                        _ => 0,
                    };
                    values.push(climate);
                }
            }
            values
        };
        assert_eq!(edge_map(42, 2, EdgeMode::CoolWarm, 0, 0, 1, 1, parent), [2]);
        assert_eq!(edge_map(42, 2, EdgeMode::HeatIce, 4, 0, 1, 1, parent), [3]);
        // Only diagonal warm land is present, so the cold cell stays cold.
        assert_eq!(edge_map(42, 2, EdgeMode::HeatIce, 0, 4, 1, 1, parent), [4]);
        assert_eq!(
            edge_map(42, 3, EdgeMode::Special, 10, 10, 1, 1, |_, _, _, _| vec![0]),
            [0]
        );
    }

    #[test]
    fn split_requests_match_negative_chunk_boundaries_for_all_modes() {
        for mode in [EdgeMode::CoolWarm, EdgeMode::HeatIce, EdgeMode::Special] {
            let whole = edge_map(42, 3, mode, -17, -17, 8, 8, patterned_parent);
            for dz in (0..8).rev() {
                for dx in (0..8).rev() {
                    let cell = edge_map(42, 3, mode, -17 + dx, -17 + dz, 1, 1, patterned_parent);
                    assert_eq!(cell[0], whole[(dz * 8 + dx) as usize]);
                }
            }
        }
    }

    #[test]
    fn zero_sized_requests_do_not_evaluate_parent() {
        for mode in [EdgeMode::CoolWarm, EdgeMode::HeatIce, EdgeMode::Special] {
            let no_parent = |_, _, _, _| -> Vec<i32> { panic!("parent called") };
            assert!(edge_map(42, 2, mode, 0, 0, 0, 8, no_parent).is_empty());
            assert!(edge_map(42, 2, mode, 0, 0, 8, 0, no_parent).is_empty());
        }
    }
}
