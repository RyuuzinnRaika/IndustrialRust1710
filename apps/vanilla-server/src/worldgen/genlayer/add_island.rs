//! Minecraft Java 1.7.10 GenLayerAddIsland (diagonal shoreline growth).
//!
//! This layer is intentionally isolated from IRW4: existing saved worlds must
//! retain their original biome mapping for not-yet-generated chunks.
use super::GenLayerRng;

/// Expand or erode land using the four diagonal neighbours, following vanilla
/// 1.7.10's reservoir-selection and RNG draw order. A value of 4 is protected
/// against erosion (the special mushroom-island marker in the GenLayer chain).
pub(super) fn add_island_map<F>(
    world_seed: i64,
    layer_salt: i64,
    x: i32,
    z: i32,
    width: usize,
    height: usize,
    parent: F,
) -> Vec<i32>
where
    F: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    // Java's int subtraction wraps for the very edge of the coordinate range.
    let parent_x = x.wrapping_sub(1);
    let parent_z = z.wrapping_sub(1);
    let parent_width = width + 2;
    let parent_height = height + 2;
    let source = parent(parent_x, parent_z, parent_width, parent_height);
    assert_eq!(source.len(), parent_width * parent_height);

    let mut result = vec![0; width * height];
    let mut rng = GenLayerRng::new(world_seed, layer_salt);
    for dz in 0..height {
        for dx in 0..width {
            let northwest = source[dz * parent_width + dx];
            let northeast = source[dz * parent_width + dx + 2];
            let southwest = source[(dz + 2) * parent_width + dx];
            let southeast = source[(dz + 2) * parent_width + dx + 2];
            let center = source[(dz + 1) * parent_width + dx + 1];
            // Java adds offsets as signed 32-bit ints before widening them
            // to longs for initChunkSeed. This matters at i32::MAX.
            rng.start_chunk(
                i64::from(x.wrapping_add(dx as i32)),
                i64::from(z.wrapping_add(dz as i32)),
            );
            let output = if center == 0
                && (northwest != 0 || northeast != 0 || southwest != 0 || southeast != 0)
            {
                // Vanilla uses a reservoir over nonzero diagonal neighbours.
                // nextInt(1) still advances the RNG and must not be skipped.
                let mut chosen = 1;
                let mut candidates = 1;
                for neighbor in [northwest, northeast, southwest, southeast] {
                    if neighbor != 0 {
                        if rng.next_int(candidates) == 0 {
                            chosen = neighbor;
                        }
                        candidates += 1;
                    }
                }
                if rng.next_int(3) == 0 || chosen == 4 {
                    chosen
                } else {
                    0
                }
            } else if center > 0
                && (northwest == 0 || northeast == 0 || southwest == 0 || southeast == 0)
            {
                if rng.next_int(5) == 0 && center != 4 {
                    0
                } else {
                    center
                }
            } else {
                center
            };
            result[dz * width + dx] = output;
        }
    }
    result
}

#[cfg(test)]
mod tests {
    use super::super::island_zoom::island_map;
    use super::*;

    fn map(seed: i64, salt: i64, x: i32, z: i32, width: usize, height: usize) -> Vec<i32> {
        add_island_map(seed, salt, x, z, width, height, |px, pz, w, h| {
            island_map(seed, px, pz, w, h)
        })
    }

    fn bits(values: &[i32]) -> String {
        values
            .iter()
            .map(|v| char::from_digit(*v as u32, 10).unwrap())
            .collect()
    }

    #[test]
    fn matches_independent_java_long_add_island_oracle() {
        // Generated by a standalone Java implementation of GenLayerIsland
        // followed by GenLayerAddIsland; not from this Rust implementation.
        for (seed, salt, x, z, expected) in [
            (
                -12_345,
                1,
                -17,
                7,
                concat!(
                    "00001000", "10000000", "00000000", "00000101", "00000000", "00000100",
                    "00000000", "00000000"
                ),
            ),
            (
                0,
                1,
                -1,
                -1,
                concat!(
                    "00000000", "01100000", "00000010", "00001010", "00000000", "10110000",
                    "00000000", "00010100"
                ),
            ),
            (
                42,
                1,
                15,
                -17,
                concat!(
                    "00001000", "00000000", "00000110", "00100000", "00000000", "00000000",
                    "00000000", "00000000"
                ),
            ),
            (
                42,
                2,
                -17,
                -17,
                concat!(
                    "10100000", "00000000", "00001000", "00010101", "00000010", "00000100",
                    "01000000", "10000000"
                ),
            ),
        ] {
            assert_eq!(bits(&map(seed, salt, x, z, 8, 8)), expected);
        }
    }

    #[test]
    fn independent_of_chunk_boundaries_and_query_order() {
        let seed = 42;
        let whole = map(seed, 1, -17, -17, 8, 8);
        for dz in (0..8).rev() {
            for dx in (0..8).rev() {
                let single = map(seed, 1, -17 + dx, -17 + dz, 1, 1);
                assert_eq!(single[0], whole[(dz * 8 + dx) as usize]);
            }
        }
        assert!(map(seed, 1, 0, 0, 0, 8).is_empty());
        assert!(map(seed, 1, 0, 0, 8, 0).is_empty());
    }


    #[test]
    fn add_island_matches_java_oracle_at_signed_coordinate_wrap() {
        // Independent Java 21 reference: parent uses Java int arithmetic,
        // and initChunkSeed receives the wrapped signed-int cell coordinates.
        // The previous widened-first implementation differs in these cases.
        fn patterned_parent(x: i32, z: i32, width: usize, height: usize) -> Vec<i32> {
            let mut values = Vec::with_capacity(width * height);
            for dz in 0..height {
                for dx in 0..width {
                    let px = x.wrapping_add(dx as i32);
                    let pz = z.wrapping_add(dz as i32);
                    let marker = px.wrapping_mul(3).wrapping_add(pz.wrapping_mul(5)) & 7;
                    values.push(if marker <= 2 {
                        0
                    } else if marker == 3 {
                        4
                    } else {
                        1
                    });
                }
            }
            values
        }

        for (seed, x, z, expected) in [
            (42_i64, i32::MAX - 1, i32::MIN, "0104101011014111"),
            (42, i32::MAX - 1, i32::MAX - 1, "0414114001041010"),
            (42, i32::MIN, i32::MAX - 1, "1411404004111040"),
            (0, i32::MAX - 1, i32::MIN, "0104101011011110"),
        ] {
            let whole = add_island_map(seed, 1, x, z, 4, 4, patterned_parent);
            assert_eq!(bits(&whole), expected, "seed={seed} x={x} z={z}");
            for dz in 0_i32..4 {
                for dx in 0_i32..4 {
                    let cell = add_island_map(
                        seed,
                        1,
                        x.wrapping_add(dx),
                        z.wrapping_add(dz),
                        1,
                        1,
                        patterned_parent,
                    );
                    assert_eq!(
                        cell[0],
                        whole[(dz * 4 + dx) as usize],
                        "split request mismatch at ({dx},{dz})"
                    );
                }
            }
        }
    }

    #[test]
    fn special_biome_four_is_preserved_during_growth_and_erosion() {
        // Center 4 with ocean diagonals cannot erode.
        let erosion = add_island_map(42, 1, -7, 3, 1, 1, |_, _, _, _| {
            vec![0, 0, 0, 0, 4, 0, 0, 0, 0]
        });
        assert_eq!(erosion, vec![4]);
        // Four diagonal 4s expand into a center 4 even when growth roll fails.
        let growth = add_island_map(42, 1, -7, 3, 1, 1, |_, _, _, _| {
            vec![4, 0, 4, 0, 0, 0, 4, 0, 4]
        });
        assert_eq!(growth, vec![4]);
    }
}
