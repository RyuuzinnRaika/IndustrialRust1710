//! Java 1.7.10 GenLayerIsland and GenLayerZoom primitives.
//!
//! These layers are deliberately not connected to the legacy IRW4 generator:
//! changing its biome mapping would alter previously ungenerated saved chunks.
//! The eventual new-world generator must select a distinct persisted version.
use super::GenLayerRng;

/// GenLayerIsland: 1 in 10 cells is land, with the origin forced to land.
/// Coordinates are layer cells, not chunk indices.
pub(super) fn island_map(world_seed: i64, x: i32, z: i32, width: usize, height: usize) -> Vec<i32> {
    let mut rng = GenLayerRng::new(world_seed, 1);
    let mut result = vec![0; width * height];
    for dz in 0..height {
        for dx in 0..width {
            rng.start_chunk(i64::from(x) + dx as i64, i64::from(z) + dz as i64);
            result[dz * width + dx] = i32::from(rng.next_int(10) == 0);
        }
    }
    // GenLayerIsland overwrites the origin after consuming the random rolls.
    // Widen before negating so even i32::MIN is safe.
    let origin_x = -i64::from(x);
    let origin_z = -i64::from(z);
    if origin_x >= 0 && origin_z >= 0 && origin_x < width as i64 && origin_z < height as i64 {
        result[origin_z as usize * width + origin_x as usize] = 1;
    }
    result
}

fn choose_two(rng: &mut GenLayerRng, a: i32, b: i32) -> i32 {
    if rng.next_int(2) == 0 {
        a
    } else {
        b
    }
}

/// GenLayerZoom's vanilla selectModeOrRandom tie-breaking order.
/// The RNG advances only if no value wins by the original priority rules.
fn mode_or_random(rng: &mut GenLayerRng, a: i32, b: i32, c: i32, d: i32) -> i32 {
    if b == c && c == d {
        return b;
    }
    if a == b && a == c {
        return a;
    }
    if a == b && a == d {
        return a;
    }
    if a == c && a == d {
        return a;
    }
    if a == b && c != d {
        return a;
    }
    if a == c && b != d {
        return a;
    }
    if a == d && b != c {
        return a;
    }
    if b == c && a != d {
        return b;
    }
    if b == d && a != c {
        return b;
    }
    if c == d && a != b {
        return c;
    }
    match rng.next_int(4) {
        0 => a,
        1 => b,
        2 => c,
        _ => d,
    }
}

/// One vanilla GenLayerZoom step over an arbitrary rectangular parent layer.
/// Uses arithmetic shift for negative coordinates and reproduces the exact
/// per-cell random draw order (south, east, then diagonal).
pub(super) fn zoom_map<F>(
    world_seed: i64,
    layer_salt: i64,
    x: i32,
    z: i32,
    width: usize,
    height: usize,
    parent: F,
) -> Vec<i32>
where
    F: Fn(i32, i32, usize, usize) -> Vec<i32>,
{
    if width == 0 || height == 0 {
        return Vec::new();
    }
    let parent_x = x >> 1;
    let parent_z = z >> 1;
    let parent_width = (width >> 1) + 2;
    let parent_height = (height >> 1) + 2;
    let source = parent(parent_x, parent_z, parent_width, parent_height);
    assert_eq!(source.len(), parent_width * parent_height);

    let stride = (parent_width - 1) * 2;
    let mut expanded = vec![0; stride * (parent_height - 1) * 2];
    let mut rng = GenLayerRng::new(world_seed, layer_salt);
    for dz in 0..parent_height - 1 {
        for dx in 0..parent_width - 1 {
            let a = source[dz * parent_width + dx];
            let b = source[dz * parent_width + dx + 1];
            let c = source[(dz + 1) * parent_width + dx];
            let d = source[(dz + 1) * parent_width + dx + 1];
            rng.start_chunk(
                (i64::from(parent_x) + dx as i64) * 2,
                (i64::from(parent_z) + dz as i64) * 2,
            );
            let index = dz * 2 * stride + dx * 2;
            expanded[index] = a;
            expanded[index + stride] = choose_two(&mut rng, a, c);
            expanded[index + 1] = choose_two(&mut rng, a, b);
            expanded[index + stride + 1] = mode_or_random(&mut rng, a, b, c, d);
        }
    }
    let mut result = vec![0; width * height];
    for dz in 0..height {
        let start = (dz + (z & 1) as usize) * stride + (x & 1) as usize;
        result[dz * width..(dz + 1) * width].copy_from_slice(&expanded[start..start + width]);
    }
    result
}

#[cfg(test)]
mod tests {
    use super::*;

    fn bits(values: &[i32]) -> String {
        values
            .iter()
            .map(|&value| match value {
                0 => '0',
                1 => '1',
                _ => panic!("unexpected non-binary island value: {value}"),
            })
            .collect()
    }

    #[test]
    fn island_matches_java_oracle_with_negative_coordinates() {
        // Generated by an independent Java-long GenLayerIsland reference.
        assert_eq!(
            bits(&island_map(-12_345, -17, 7, 8, 8)),
            concat!(
                "01000000", "00001000", "00010000", "10000000", "00000010", "00000000", "00000000",
                "00000000"
            )
        );
        assert_eq!(island_map(0, -1, -1, 3, 3)[4], 1);
        assert_eq!(island_map(42, i32::MIN, i32::MIN, 1, 1).len(), 1);
    }

    #[test]
    fn zoom_matches_java_oracle_on_negative_odd_coordinates() {
        let map = zoom_map(-12_345, 2000, -17, 7, 8, 8, |x, z, w, h| {
            island_map(-12_345, x, z, w, h)
        });
        assert_eq!(
            bits(&map),
            concat!(
                "00000100", "10000000", "11000000", "11000000", "00000000", "00000000", "00000000",
                "00000000"
            )
        );
    }

    #[test]
    fn zoom_matches_java_oracle_at_origin() {
        let map = zoom_map(0, 2000, 0, 0, 8, 8, |x, z, w, h| island_map(0, x, z, w, h));
        assert_eq!(
            bits(&map),
            concat!(
                "11000000", "00000000", "00011000", "00001000", "00000000", "00000000", "10000000",
                "00000000"
            )
        );
    }

    #[test]
    fn zoom_is_stable_across_negative_region_boundaries() {
        let seed = 42;
        let whole = zoom_map(seed, 2000, -17, 7, 8, 8, |x, z, w, h| {
            island_map(seed, x, z, w, h)
        });
        for dz in 0..8 {
            for dx in 0..8 {
                let cell = zoom_map(seed, 2000, -17 + dx, 7 + dz, 1, 1, |x, z, w, h| {
                    island_map(seed, x, z, w, h)
                });
                assert_eq!(cell[0], whole[(dz * 8 + dx) as usize]);
            }
        }
    }
}
